#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';

const outDir = process.cwd();
const now = new Date();
const ts = now.toISOString().replace(/[:.]/g, '-');
const outFile = path.join(outDir, `mock_call_billing_${ts}.sql`);

const DEFAULT_TENANTS = (process.env.TENANT_IDS || '').split(',').filter(Boolean);
const tenants = DEFAULT_TENANTS.length ? DEFAULT_TENANTS : ['tenant-demo-1', 'tenant-demo-2'];

const CALL_OUTCOMES = [
  'call_failed',
  'busy_line',
  'invalid_number',
  'voicemail_detected',
  'user_no_response',
  'wrong_person',
  'not_available_callback_requested',
  'not_interested',
  'already_purchased',
  'budget_not_decided',
  'timeline_long_term',
  'details_requested',
  'advisor_callback_scheduled',
  'qualified_lead_buy',
  'site_visit_scheduled',
];

// Outcomes we treat as non-billable (zero debit)
const NON_BILLABLE = new Set([
  'voicemail_detected',
  'busy_line',
  'invalid_number',
  'user_no_response',
  'wrong_person',
  'call_failed',
  'not_available_callback_requested',
]);

const DURATIONS = [0, 5, 30, 61, 180, 240, 600]; // seconds

function uuid(){
  if (crypto.randomUUID) return crypto.randomUUID();
  return ([1e7]+-1e3+-4e3+-8e3+-1e11).replace(/[018]/g, c=>
    (c ^ crypto.randomBytes(1)[0] & 15 >> c / 4).toString(16)
  );
}

function iso(d){ return new Date(d).toISOString(); }

function sqlEscapeJson(obj){ return JSON.stringify(obj).replace(/'/g, "''"); }

function writeFile(content){ fs.writeFileSync(outFile, content, { encoding: 'utf8' }); }

function build(){
  const lines = [];
  lines.push('-- Mock call billing SQL generated by scripts/generate-mock-call-billing.mjs');
  lines.push('BEGIN;');

  const batchId = uuid();

  tenants.forEach((tenantId, tIdx) => {
    // create a wallet account for tenant
    const walletAccountId = uuid();
    const walletAccountCreated = now.toISOString();
    lines.push(`-- Tenant: ${tenantId}`);
    lines.push(
      `INSERT INTO "WalletAccount" ("id","tenantId","userId","currency","status","currentBalanceMinor","createdAt","updatedAt") VALUES ('${walletAccountId}','${tenantId}',NULL,'INR','active',100000,'${walletAccountCreated}','${walletAccountCreated}');`
    );

    CALL_OUTCOMES.forEach((outcome, oIdx) => {
      DURATIONS.forEach((duration) => {
        const callId = uuid();
        const sessionId = callId;
        const initiatedAt = new Date(now.getTime() - Math.floor(Math.random()*1000*60*60)).toISOString();
        const completedAt = duration > 0 ? new Date(new Date(initiatedAt).getTime() + duration*1000).toISOString() : initiatedAt;
        const createdAt = iso(now);

        const callStatus = duration > 0 && !NON_BILLABLE.has(outcome) ? 'completed' : (NON_BILLABLE.has(outcome) ? 'completed' : 'failed');

        // CallSession
        lines.push(`INSERT INTO "CallSession" ("id","tenantId","externalCallId","roomId","phoneNumber","agentName","direction","status","initiatedAt","connectedAt","completedAt","durationSec","transcriptTurns","recordingUrl","estimatedCost","lastError","callOutcome","endedBy","confidence","createdAt","updatedAt") VALUES ('${sessionId}','${tenantId}',NULL,'room-${sessionId}','+919999000${tIdx}${oIdx}','agent-${tIdx}','outbound','${callStatus}','${initiatedAt}','${initiatedAt}','${completedAt}',${duration},0,NULL,NULL,NULL,'${outcome}',NULL,${(Math.random()*0.4+0.5).toFixed(2)},'${createdAt}','${createdAt}');`);

        // CallEvent (call_analysis_completed)
        const eventId = uuid();
        const occurredAt = completedAt;
        const payload = {
          call_id: sessionId,
          started_at: initiatedAt,
          duration_sec: duration,
          status: 'completed',
          lead: { property_type: null, location: null, budget: null, timeline: null },
          call_outcome: outcome,
          confidence: parseFloat((Math.random()*0.4+0.5).toFixed(2)),
        };
        lines.push(`INSERT INTO "CallEvent" ("id","callId","tenantId","eventType","occurredAt","eventId","payloadJson","rawEnvelope","rawHeaders","normalizedJson","createdAt") VALUES ('${uuid()}','${sessionId}','${tenantId}','call_analysis_completed','${occurredAt}','${eventId}','${sqlEscapeJson(payload)}',NULL,NULL,NULL,'${createdAt}');`);

        // compute billing
        const perMinuteRatePaise = 540; // default from prisma
        const billedMinutes = Math.ceil(Math.max(0,duration)/60);
        const debitAmountPaise = NON_BILLABLE.has(outcome) || billedMinutes === 0 ? 0 : billedMinutes * perMinuteRatePaise;

        // WalletLedger (debit) only if debitAmountPaise > 0
        let walletLedgerId = null;
        if (debitAmountPaise > 0){
          walletLedgerId = uuid();
          lines.push(`INSERT INTO "WalletLedger" ("id","tenantId","walletAccountId","direction","amountMinor","currency","status","entryType","description","createdAt","updatedAt") VALUES ('${walletLedgerId}','${tenantId}','${walletAccountId}','debit',${debitAmountPaise},'INR','posted','call_billing','Call billing for call ${sessionId}', '${createdAt}','${createdAt}');`);
        }

        // CallBillingTransaction
        const cbId = uuid();
        const callStatusText = outcome;
        const transactionMeta = { outcome, duration, billedMinutes };
        lines.push(`INSERT INTO "CallBillingTransaction" ("id","tenantId","batchId","leadId","callId","walletAccountId","walletLedgerId","callDurationSeconds","billedMinutes","perMinuteRatePaise","debitAmountPaise","callStatus","transactionMetaJson","createdAt","updatedAt") VALUES ('${cbId}','${tenantId}','${batchId}',NULL,'${sessionId}','${walletAccountId}',${walletLedgerId?`'${walletLedgerId}'`: 'NULL'},${duration},${billedMinutes},${perMinuteRatePaise},${debitAmountPaise},'${callStatusText}','${sqlEscapeJson(transactionMeta)}','${createdAt}','${createdAt}');`);

      });
    });
  });

  lines.push('COMMIT;');
  return lines.join('\n');
}

const sql = build();
writeFile(sql);
console.log('Wrote', outFile);
